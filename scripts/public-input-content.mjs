function deliverableConstraints(item, requiredIds) {
  return [
    "Use only claims supported by the supplied documents and prior records.",
    `Cite the decision evidence with [${requiredIds[0]}] and [${requiredIds[1]}].`,
    item.hardConstraint,
    "Separate observed facts, interpretation, and recommendation.",
  ];
}

function buildDocuments(item) {
  return item.documents.map((document, index) => {
    const documentId = `doc-${String(index + 1).padStart(2, "0")}`;
    return {
      documentId,
      documentType: document.type,
      title: document.title,
      authorRole: document.authorRole,
      recordedAt: document.recordedAt,
      content: document.content,
      source: `synthetic://openboa-ai/coffee-chat-bench/${item.caseId}/${documentId}`,
      license: "MIT",
    };
  });
}

export function buildCaseBlueprint({ caseIndex }) {
  const item = CASE_DEFINITIONS[caseIndex];
  if (!item) throw new Error(`unknown case index ${caseIndex}`);
  const offset = caseIndex % item.documents.length;
  const orderedDocuments = item.documents.map(
    (_, index) => item.documents[(index + offset) % item.documents.length],
  );
  const documents = buildDocuments({ ...item, documents: orderedDocuments });
  const requiredDocuments = item.required.map((index) => item.documents[index]);
  const requiredReferenceIds = requiredDocuments.map(
    (requiredDocument) =>
      documents[orderedDocuments.indexOf(requiredDocument)].documentId,
  );
  return {
    caseId: item.caseId,
    pairId: item.pairId,
    form: item.form,
    domain: item.domain,
    transferType: item.transferType,
    taskArchetype: item.taskArchetype,
    taskMode: item.taskMode,
    task: {
      instruction: item.instruction,
      deliverables: item.deliverables,
      hardConstraints: deliverableConstraints(item, requiredReferenceIds),
      requiredReferenceIds,
    },
    documents,
    annotations: {
      caseId: item.caseId,
      pairId: item.pairId,
      domain: item.domain,
      transferType: item.transferType,
      form: item.form,
      taskArchetype: item.taskArchetype,
      taskMode: item.taskMode,
      documentCount: documents.length,
      documentRoles: documents.map((document, index) => ({
        documentId: document.documentId,
        role: orderedDocuments[index].role,
      })),
      userScenario: item.caseId,
      workspaceNoise: item.documents.some(({ role }) => role === "competing")
        ? "noisy"
        : "ordinary",
      historyNecessity:
        "target-specific judgment cannot be recovered from task documents alone",
      transferIntegrity:
        "no held-out entity, option, quantity, or answer appears in the matched history",
      reviewStatus: "pending_human_audit",
    },
  };
}

export function buildPairAnnotation(pairIndex) {
  const item = PAIR_DEFINITIONS[pairIndex];
  if (!item) throw new Error(`unknown pair index ${pairIndex}`);
  return {
    pairId: item.pairId,
    contrastFamily: item.contrastFamily,
    historyRecords: 8,
    distinctDecisionsPerTarget: 8,
    convergentBoundaryEpisodes: 2,
    rationaleAvailability: "partial",
    reviewStatus: "pending_human_audit",
  };
}

export function buildAllInputContent() {
  const pairHistories = PAIR_DEFINITIONS.map((_, index) =>
    buildPairHistories(index),
  );
  return {
    pairs: PAIR_DEFINITIONS,
    cases: CASE_DEFINITIONS.map((_, caseIndex) => {
      const blueprint = buildCaseBlueprint({ caseIndex });
      const pairIndex = PAIR_DEFINITIONS.findIndex(
        ({ pairId }) => pairId === blueprint.pairId,
      );
      return { blueprint, histories: pairHistories[pairIndex] };
    }),
    pairHistories,
  };
}

