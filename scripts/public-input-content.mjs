function historyContent(pairId, index, format, item, decision) {
  const ref = `[history-${pairId.slice(-2)}-${String(index + 1).padStart(2, "0")}-fact]`;
  const prefix = `Situation: ${item.situation}\nShared facts ${ref}: ${item.evidence}`;
  const decisionLine =
    format === "decision_note"
      ? `Decision: ${decision}`
      : format === "message_excerpt"
        ? `Message excerpt: ${decision}`
        : format === "retrospective"
          ? `Retrospective: ${decision}`
          : `log.decision=${decision}`;
  const rationale =
    item.rationale && index % 2 === 0 ? `\nReasoning: ${item.rationale}` : "";
  return `${prefix}\n${decisionLine}${rationale}`;
}

export function buildPairHistories(pairIndex) {
  const definition = PAIR_DEFINITIONS[pairIndex];
  if (!definition) throw new Error(`unknown pair index ${pairIndex}`);
  return {
    target_a: definition.episodes.map((item, index) => ({
      id: `record-${String(index + 1).padStart(2, "0")}`,
      format: FORMATS[index],
      content: historyContent(
        definition.pairId,
        index,
        FORMATS[index],
        item,
        item.aDecision,
      ),
    })),
    target_b: definition.episodes.map((item, index) => ({
      id: `record-${String(index + 1).padStart(2, "0")}`,
      format: FORMATS[index],
      content: historyContent(
        definition.pairId,
        index,
        FORMATS[index],
        item,
        item.bDecision,
      ),
    })),
  };
}

function doc(role, type, title, authorRole, recordedAt, content) {
  return { role, type, title, authorRole, recordedAt, content };
}

function caseDefinition(value) {
  if (value.documents.length < 5 || value.documents.length > 9)
    throw new Error(`${value.caseId} needs five to nine documents`);
  return value;
}

